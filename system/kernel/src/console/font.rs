const fn row_bits(s: &str) -> u8 {
    let b = s.as_bytes();
    let mut v = 0u8;
    let mut i = 0;
    while i < 5 {
        v = v << 1 | (b[i] == b'#') as u8;
        i += 1;
    }
    v
}

/// Box-drawing pieces as (left, right, up, down) arms.
const BOX: &[(u8, [bool; 4])] = &[
    (0xC4, [true, true, false, false]), // ─
    (0xB3, [false, false, true, true]), // │
    (0xDA, [false, true, false, true]), // ┌
    (0xBF, [true, false, false, true]), // ┐
    (0xC0, [false, true, true, false]), // └
    (0xD9, [true, false, true, false]), // ┘
    (0xC3, [false, true, true, true]),  // ├
    (0xB4, [true, false, true, true]),  // ┤
    (0xC2, [true, true, false, true]),  // ┬
    (0xC1, [true, true, true, false]),  // ┴
    (0xC5, [true, true, true, true]),   // ┼
];

const fn build() -> [u8; 4096] {
    let mut font = [0u8; 4096];
    let mut g = 0;
    while g < GLYPHS.len() {
        let (code, rows) = GLYPHS[g];
        let mut r = 0;
        while r < 7 {
            let bits = row_bits(rows[r]) << 2;
            font[code as usize * 16 + 1 + r * 2] = bits;
            font[code as usize * 16 + 2 + r * 2] = bits;
            r += 1;
        }
        g += 1;
    }
    let mut b = 0;
    while b < BOX.len() {
        let (code, [l, rt, up, dn]) = BOX[b];
        let base = code as usize * 16;
        let mut y = 0;
        while y < 16 {
            let mut v = 0u8;
            if y == 7 {
                if l {
                    v |= 0xF8;
                }
                if rt {
                    v |= 0x1F;
                }
            }
            if (up && y <= 7) || (dn && y >= 7) {
                v |= 0x18;
            }
            font[base + y] = v;
            y += 1;
        }
        b += 1;
    }
    // Blocks and shades.
    let mut y = 0;
    while y < 16 {
        font[0xDB * 16 + y] = 0xFF; // █
        font[0xB0 * 16 + y] = if y % 2 == 0 { 0x88 } else { 0x22 }; // ░
        font[0xB1 * 16 + y] = if y % 2 == 0 { 0xAA } else { 0x55 }; // ▒
        font[0xB2 * 16 + y] = if y % 2 == 0 { 0xEE } else { 0xBB }; // ▓
        font[0xDC * 16 + y] = if y >= 8 { 0xFF } else { 0 }; // ▄
        font[0xDF * 16 + y] = if y < 8 { 0xFF } else { 0 }; // ▀
        font[0xFE * 16 + y] = if y >= 4 && y < 12 { 0x7E } else { 0 }; // ■
        font[0x07 * 16 + y] = if y >= 6 && y < 10 { 0x3C } else { 0 }; // •
        font[0xFA * 16 + y] = if y >= 7 && y < 9 { 0x18 } else { 0 }; // ·
        y += 1;
    }
    font
}

pub static FONT: [u8; 4096] = build();
