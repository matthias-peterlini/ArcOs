//! Unicode to code page 437, the layout of the BIOS font.

const HIGH: [char; 128] = [
    'Ç', 'ü', 'é', 'â', 'ä', 'à', 'å', 'ç', 'ê', 'ë', 'è', 'ï', 'î', 'ì', 'Ä', 'Å', //
    'É', 'æ', 'Æ', 'ô', 'ö', 'ò', 'û', 'ù', 'ÿ', 'Ö', 'Ü', '¢', '£', '¥', '₧', 'ƒ', //
    'á', 'í', 'ó', 'ú', 'ñ', 'Ñ', 'ª', 'º', '¿', '⌐', '¬', '½', '¼', '¡', '«', '»', //
    '░', '▒', '▓', '│', '┤', '╡', '╢', '╖', '╕', '╣', '║', '╗', '╝', '╜', '╛', '┐', //
    '└', '┴', '┬', '├', '─', '┼', '╞', '╟', '╚', '╔', '╩', '╦', '╠', '═', '╬', '╧', //
    '╨', '╤', '╥', '╙', '╘', '╒', '╓', '╫', '╪', '┘', '┌', '█', '▄', '▌', '▐', '▀', //
    'α', 'ß', 'Γ', 'π', 'Σ', 'σ', 'µ', 'τ', 'Φ', 'Θ', 'Ω', 'δ', '∞', 'φ', 'ε', '∩', //
    '≡', '±', '≥', '≤', '⌠', '⌡', '÷', '≈', '°', '∙', '·', '√', 'ⁿ', '²', '■', ' ', //
];

/// Glyph index of `c` in the BIOS font, or `?` if it has none.
pub fn glyph(c: char) -> u8 {
    match c {
        ' '..='~' => c as u8,
        '§' => 0x15,
        '¶' => 0x14,
        '•' => 0x07,
        '►' => 0x10,
        '◄' => 0x11,
        '↑' => 0x18,
        '↓' => 0x19,
        '→' => 0x1A,
        '←' => 0x1B,
        '▲' => 0x1E,
        '▼' => 0x1F,
        '♥' => 0x03,
        '♦' => 0x04,
        '☺' => 0x01,
        'È' => b'E',
        'À' => b'A',
        'Ì' => b'I',
        'Ò' => b'O',
        'Ù' => b'U',
        '€' => b'E',
        '›' => b'>',
        '‹' => b'<',
        '…' => 0xFA,
        '—' | '–' => 0xC4,
        '✓' => 0xFB,
        '●' | '◆' => 0x04,
        _ => HIGH.iter().position(|&h| h == c).map(|i| 0x80 + i as u8).unwrap_or(b'?'),
    }
}

/// The character glyph `b` of the BIOS font shows (the inverse of [`glyph`]).
pub fn to_char(b: u8) -> char {
    match b {
        0x20..=0x7E => b as char,
        0x80..=0xFF => HIGH[(b - 0x80) as usize],
        0x15 => '§',
        0x14 => '¶',
        0x07 => '•',
        0x10 => '►',
        0x11 => '◄',
        0x18 => '↑',
        0x19 => '↓',
        0x1A => '→',
        0x1B => '←',
        0x1E => '▲',
        0x1F => '▼',
        0x03 => '♥',
        0x04 => '♦',
        _ => ' ',
    }
}
